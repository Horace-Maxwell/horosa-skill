#!/usr/bin/env python3
"""Render `docs/ENV_VARS.md` from the env registry (v0.50.0-dev, E-15).

The registry (`config.ENV_FLAG_REGISTRY`, tier per variable) and the one-line descriptions next to it
(`env_docs.ENV_FLAG_DOCS`) are the only source; the document is build output.

    uv run python scripts/gen_env_reference.py            # (re)write docs/ENV_VARS.md
    uv run python scripts/gen_env_reference.py --check    # exit 1 when the file differs from the render

`tests/test_env_reference.py` runs the check, so a variable added to the registry without a description, or a
document that was not regenerated, fails the suite.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

for _stream in (sys.stdout, sys.stderr):
    _reconfigure = getattr(_stream, "reconfigure", None)
    if _reconfigure is not None:
        _reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "docs" / "ENV_VARS.md"
sys.path.insert(0, str(ROOT / "horosa-skill" / "src"))

_TIERS = (
    ("stable", "Stable — documented, for users / 稳定：给用户用的"),
    ("experimental", "Experimental — may change / 试验：可能会变"),
    ("internal", "Internal — build machines, scripts, launcher plumbing; normally not set by hand / 内部：构建机、脚本、启动器机务，一般不手设"),
    ("deprecated", "Deprecated — still read, prefer the replacement / 劝退：仍会读，请改用替代项"),
)


def render() -> str:
    from horosa_skill.config import ENV_FLAG_REGISTRY, REMOVED_ENV_FLAGS
    from horosa_skill.env_docs import ENV_FLAG_DOCS

    missing = sorted(set(ENV_FLAG_REGISTRY) - set(ENV_FLAG_DOCS))
    stray = sorted(set(ENV_FLAG_DOCS) - set(ENV_FLAG_REGISTRY))
    if missing or stray:
        raise SystemExit(f"env_docs.ENV_FLAG_DOCS out of step with the registry: missing={missing} stray={stray}")
    lines = [
        "# 环境变量 / Environment variables",
        "",
        "<!-- Generated by horosa-skill/scripts/gen_env_reference.py from config.ENV_FLAG_REGISTRY + env_docs.ENV_FLAG_DOCS. Do not edit by hand. -->",
        "",
        f"Every `HOROSA_*` variable the skill knows ({len(ENV_FLAG_REGISTRY)}). An unknown `HOROSA_*` name is warned about once and",
        "ignored (`HOROSA_STRICT_CONFIG=1` makes it an error). A value that cannot be parsed falls back to the default and",
        "`doctor` names it (`env:rejected_value`, provenance `default:rejected env:<NAME>=…`); a service URL without",
        "`http://` is kept but flagged (`env:invalid_url`). Values of names that look like keys or tokens are never printed.",
        "",
        "本工具认得的全部 `HOROSA_*` 变量。未知名字告警一次并忽略；认不出的值回落默认值，`doctor` 会点名；密钥 / 令牌类的值永不回显。",
        "",
    ]
    for tier, title in _TIERS:
        names = sorted(name for name, value in ENV_FLAG_REGISTRY.items() if value == tier)
        if not names:
            continue
        lines += [f"## {title}", "", "| Variable | What it does |", "| --- | --- |"]
        lines += [f"| `{name}` | {ENV_FLAG_DOCS[name].replace('|', '\\|')} |" for name in names]
        lines.append("")
    if REMOVED_ENV_FLAGS:
        lines += ["## Removed / 已移除", "", "| Variable | Replacement |", "| --- | --- |"]
        lines += [f"| `{name}` | {text} |" for name, text in sorted(REMOVED_ENV_FLAGS.items())]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/ENV_VARS.md differs from the render")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is stale: run `uv run python scripts/gen_env_reference.py`", file=sys.stderr)
            return 1
        print("env reference OK")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
